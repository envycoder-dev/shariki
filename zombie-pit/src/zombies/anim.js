// Процедурные анимации: циклы походки по типам (с индивидуальным стилем каждого зомби)
// и ключевые клипы (вылезание из ямы, атаки, смерти). Всё пишет в плоскую позу (см. rig.js).
import { B, BONES, HIPS_P, ROOT_P, ROOT_R, POSE_SIZE } from './rig.js';

const PI = Math.PI;
const S = (bone, axis) => B[bone] * 3 + axis;
const set = (p, bone, x, y, z) => { const i = B[bone] * 3; p[i] = x; p[i + 1] = y; p[i + 2] = z; };
const pos = (v) => (v > 0 ? v : 0);

export function neutral(p) {
  p.fill(0);
  set(p, 'spine', 0.06, 0, 0); set(p, 'chest', 0.03, 0, 0); set(p, 'neck', 0.08, 0, 0);
  set(p, 'armL', -0.12, 0, 0.1); set(p, 'armR', -0.12, 0, -0.1);
  set(p, 'foreL', -0.3, 0, 0); set(p, 'foreR', -0.3, 0, 0);
  set(p, 'jaw', 0.08, 0, 0);
}

// ------------------------------------------------------------------ походки
// st — индивидуальный стиль: stride, limp, limpSide, arms (0 тянет руки, 1 висят, 2 одна тянется), lean, tilt, twitch, seed
function legs(p, ph, amp, kneeAmp, kneeBase, footAmp, st, abd) {
  for (const [side, a, sx] of [['L', ph, 1], ['R', ph + PI, -1]]) {
    const bad = st.limp > 0 && sx === st.limpSide;
    const am = amp * (bad ? 1 - 0.55 * st.limp : 1);
    const s = Math.sin(a);
    const k = kneeBase + kneeAmp * (bad ? 0.35 : 1) * Math.pow(pos(Math.cos(a + 0.7)), 2);
    const i = B['thigh' + side] * 3;
    p[i] = -am * s - 0.05; p[i + 1] = bad ? sx * 0.3 * st.limp : 0; p[i + 2] = sx * abd;
    p[B['shin' + side] * 3] = k;
    p[B['foot' + side] * 3] = -footAmp * s + (bad ? 0.2 * st.limp : 0);
  }
}

export function gaitWalk(p, ph, t, st) {
  neutral(p);
  const sp = st.stride;
  legs(p, ph, 0.3 * sp, 0.6 * sp, 0.1, 0.22, st, 0.045);
  const badStance = st.limp > 0 ? pos(st.limpSide > 0 ? -Math.cos(ph) : Math.cos(ph)) : 0;
  p[HIPS_P] = -0.035 * Math.cos(ph);
  p[HIPS_P + 1] = -0.03 * sp * (1 - Math.cos(2 * ph)) * 0.5 - 0.02 - 0.05 * st.limp * badStance;
  p[S('hips', 1)] = -0.12 * Math.sin(ph);
  p[S('hips', 2)] = 0.04 * Math.cos(ph) - 0.08 * st.limp * badStance * st.limpSide;
  p[S('spine', 0)] = 0.14 + st.lean;
  p[S('spine', 2)] = 0.06 * st.limp * st.limpSide + 0.03 * Math.cos(ph);
  p[S('chest', 0)] = 0.06 + 0.03 * Math.cos(2 * ph);
  p[S('chest', 1)] = 0.1 * Math.sin(ph);
  p[S('neck', 0)] = 0.12 + 0.04 * Math.cos(2 * ph + 0.5);
  p[S('head', 0)] = -0.12; p[S('head', 2)] = st.tilt;
  const bob = 0.07 * Math.cos(2 * ph);
  const drift = (k) => 0.12 * Math.sin(t * (0.7 + k * 0.23) + st.seed * (1 + k));
  const reach = (side, sx, k) => {
    set(p, 'arm' + side, -1.3 + bob + drift(k) * 0.6, 0, sx * (0.14 + 0.06 * Math.sin(t * 0.9 + k)));
    p[S('fore' + side, 0)] = -0.22 - 0.1 * Math.sin(t * 1.3 + k * 2);
    p[S('hand' + side, 0)] = 0.45;
  };
  const hang = (side, sx, k, limp) => {
    const sw = (limp ? 0.32 : 0.22) * Math.sin(ph + (sx > 0 ? 0 : PI));
    set(p, 'arm' + side, sw + 0.05, limp ? sx * 0.25 : 0, sx * (limp ? 0.04 : 0.1));
    p[S('fore' + side, 0)] = limp ? -0.05 : -0.25 + 0.1 * Math.sin(ph * 2);
    p[S('hand' + side, 0)] = limp ? 0.1 : 0;
  };
  if (st.arms === 0) { reach('L', 1, 0); reach('R', -1, 1); }
  else if (st.arms === 1) { hang('L', 1, 0, false); hang('R', -1, 1, false); }
  else { reach(st.limpSide > 0 ? 'R' : 'L', st.limpSide > 0 ? -1 : 1, 0); hang(st.limpSide > 0 ? 'L' : 'R', st.limpSide > 0 ? 1 : -1, 1, true); }
  p[S('jaw', 0)] = 0.1 + 0.22 * pos(Math.sin(t * 1.3 + st.seed));
}

export function gaitRun(p, ph, t, st) {
  neutral(p);
  for (const [side, a] of [['L', ph], ['R', ph + PI]]) {
    const s = Math.sin(a);
    p[S('thigh' + side, 0)] = -0.75 * s - 0.25;
    p[S('shin' + side, 0)] = 0.25 + 1.55 * Math.pow(pos(Math.cos(a + 0.6)), 1.5);
    p[S('foot' + side, 0)] = -0.3 * s + 0.1;
  }
  p[HIPS_P + 1] = -0.05 + 0.05 * Math.abs(Math.sin(ph));
  p[S('hips', 1)] = -0.18 * Math.sin(ph);
  p[S('spine', 0)] = 0.38 + st.lean;
  p[S('chest', 0)] = 0.12; p[S('chest', 1)] = 0.22 * Math.sin(ph);
  p[S('neck', 0)] = -0.2 + 0.08 * Math.sin(2 * ph); p[S('head', 0)] = -0.25; p[S('head', 2)] = st.tilt * 0.6;
  p[S('jaw', 0)] = 0.35 + 0.15 * Math.sin(t * 9);
  if (st.arms === 1) { // работает руками как спринтер
    for (const [side, sx, a] of [['L', 1, ph], ['R', -1, ph + PI]]) {
      set(p, 'arm' + side, 0.85 * Math.sin(a) - 0.25, 0, sx * 0.18);
      p[S('fore' + side, 0)] = -1.35 + 0.2 * Math.sin(a);
    }
  } else { // руки вперёд, хаотично хватают воздух
    for (const [side, sx, k] of [['L', 1, 0], ['R', -1, 2.1]]) {
      set(p, 'arm' + side, -1.45 + 0.35 * Math.sin(ph * 2 + k) + 0.15 * Math.sin(t * 7 + k), 0, sx * (0.2 + 0.12 * Math.sin(t * 5 + k)));
      p[S('fore' + side, 0)] = -0.35 - 0.3 * pos(Math.sin(t * 6 + k));
      p[S('hand' + side, 0)] = 0.3;
    }
  }
}

/** ползком: тело почти горизонтально, руки по очереди подтягивают; legless — без ног */
export function gaitCrawl(p, ph, t, st, legless) {
  neutral(p);
  p[ROOT_R] = 1.42 + 0.05 * Math.sin(2 * ph);
  p[ROOT_P + 1] = 0.0;
  p[S('spine', 0)] = -0.12; p[S('spine', 2)] = 0.1 * Math.sin(ph);
  p[S('chest', 0)] = -0.12; p[S('chest', 1)] = 0.12 * Math.sin(ph);
  p[S('neck', 0)] = -0.62; p[S('head', 0)] = -0.45; p[S('head', 2)] = st.tilt;
  for (const [side, sx, a] of [['L', 1, ph], ['R', -1, ph + PI]]) {
    const c = Math.cos(a);
    set(p, 'arm' + side, -1.95 - 0.75 * c, 0, sx * (0.42 + 0.12 * Math.sin(a)));
    p[S('fore' + side, 0)] = -0.25 - 0.95 * pos(Math.sin(a));
    p[S('hand' + side, 0)] = -0.2 + 0.3 * c;
  }
  if (!legless) {
    p[S('thighL', 0)] = 0.05 + 0.08 * Math.sin(ph); p[S('shinL', 0)] = 0.35 + 0.2 * Math.sin(ph + 1);
    p[S('thighR', 0)] = 0.1 - 0.08 * Math.sin(ph); p[S('shinR', 0)] = 0.7;
    p[S('thighL', 2)] = 0.1; p[S('thighR', 2)] = -0.15;
  }
  p[S('jaw', 0)] = 0.2 + 0.3 * pos(Math.sin(t * 2.1 + st.seed));
}

export function gaitBrute(p, ph, t, st) {
  neutral(p);
  legs(p, ph, 0.34, 0.55, 0.14, 0.2, st, 0.11);
  p[HIPS_P] = -0.06 * Math.cos(ph);
  p[HIPS_P + 1] = -0.06 * (1 - Math.cos(2 * ph)) * 0.5 - 0.04;
  p[S('hips', 1)] = -0.1 * Math.sin(ph); p[S('hips', 2)] = 0.06 * Math.cos(ph);
  p[S('spine', 0)] = 0.22; p[S('chest', 0)] = 0.1;
  p[S('chest', 1)] = 0.2 * Math.sin(ph); p[S('chest', 2)] = -0.1 * Math.cos(ph);
  p[S('neck', 0)] = 0.35; p[S('head', 0)] = -0.32;
  for (const [side, sx, a] of [['L', 1, ph], ['R', -1, ph + PI]]) {
    set(p, 'arm' + side, 0.35 * Math.sin(a) - 0.1, 0, sx * 0.36);
    p[S('fore' + side, 0)] = -0.45 - 0.15 * Math.sin(a);
    p[S('hand' + side, 0)] = 0.15;
  }
  p[S('jaw', 0)] = 0.15 + 0.2 * pos(Math.sin(t * 0.9 + st.seed));
}

export function gaitSpitter(p, ph, t, st) {
  neutral(p);
  legs(p, ph, 0.36, 0.7, 0.2, 0.25, st, 0.06);
  p[HIPS_P + 1] = -0.07 - 0.03 * (1 - Math.cos(2 * ph)) * 0.5;
  p[S('hips', 1)] = -0.14 * Math.sin(ph);
  p[S('spine', 0)] = 0.45; p[S('chest', 0)] = 0.25; p[S('chest', 1)] = 0.12 * Math.sin(ph);
  const jerk = Math.sin(t * 2.3 + st.seed) > 0.85 ? 0.25 * Math.sin(t * 40) : 0;
  p[S('neck', 0)] = 0.55 + jerk * 0.3; p[S('head', 0)] = -0.62; p[S('head', 1)] = jerk; p[S('head', 2)] = st.tilt;
  for (const [side, sx, a] of [['L', 1, ph], ['R', -1, ph + PI]]) {
    set(p, 'arm' + side, -0.45 + 0.25 * Math.sin(a), 0, sx * 0.16);
    p[S('fore' + side, 0)] = -0.6 - 0.2 * Math.sin(a + 1);
    p[S('hand' + side, 0)] = 0.35;
  }
  p[S('jaw', 0)] = 0.3 + 0.2 * Math.sin(t * 3);
}

