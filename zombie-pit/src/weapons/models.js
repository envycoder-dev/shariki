// Процедурные модели оружия. Каждая функция возвращает { root, ...анимируемые узлы, точки (дуло, экстрактор), высота линии прицела }.
// Профили [f, u, r]: f — вперёд от тыльного торца, u — вверх. Статика сливается по материалам, движущиеся детали — отдельные меши.
import * as THREE from 'three';
import { Parts, side, prism, top, lathe, box, cylX, xf } from './geom.js';

const D2R = Math.PI / 180;

// Капсюль/заклёпка: приплюснутая полусфера на боковой грани
function rivet(P, mat, x, u, f, r = 0.0021, color = 0xffffff) {
  const g = new THREE.SphereGeometry(r, 10, 6);
  xf(g, x, u, -f, 0, 0, 0, 0.45, 1, 1);
  P.add(mat, g, color, 0);
}

// ───────────────────────────── Пистолет (9 мм, полимерная рамка) ─────────────────────────────
export function buildPistol(M) {
  const root = new THREE.Group(); root.name = 'pistol';
  const P = new Parts();
  // --- затвор: набор поперечных сечений (насечки = чередование узких и полных срезов) ---
  const S = new Parts();
  const w2 = 0.01275, h = 0.0295, c = 0.0034;
  const full = [[-w2, 0.0006, 0.0005], [w2, 0.0006, 0.0005], [w2, h - c, 0.0012], [w2 - c * 0.85, h, 0.001], [-w2 + c * 0.85, h, 0.001], [-w2, h - c, 0.0012]];
  const groove = full.map((p) => [p[0] * 0.935, p[1], p[2]]);
  const port = [[-w2, 0.0006, 0.0005], [w2, 0.0006, 0.0005], [w2, 0.0125, 0.0005], [-0.0042, 0.0125, 0.0004], [-0.0042, h, 0.0004], [-w2 + c * 0.85, h, 0.001], [-w2, h - c, 0.0012]];
  const seq = [[full, 0, 0.006]];
  let f = 0.006;
  for (let i = 0; i < 9; i++, f += 0.0044) { seq.push([groove, f, f + 0.0019]); seq.push([full, f + 0.0019, f + 0.0044]); }
  seq.push([full, f, 0.072], [port, 0.072, 0.114], [full, 0.114, 0.128]);
  f = 0.128;
  for (let i = 0; i < 7; i++, f += 0.0044) { seq.push([groove, f, f + 0.0019]); seq.push([full, f + 0.0019, f + 0.0044]); }
  seq.push([full, f, 0.1835]);
  for (const [pts, a, b] of seq) S.add('steel', prism(pts, a, b, { cs: 3 }));
  // скошенный «нос» затвора
  const nose = full.map((p) => [p[0] * 0.9, p[1] < 0.01 ? p[1] + 0.0012 : p[1] - 0.0009, p[2]]);
  S.add('steel', prism(nose, 0.1835, 0.186, { cs: 3 }));
  // прицелы: целик с прорезью и мушка
  const rear = [[-0.0105, h - 0.0005], [0.0105, h - 0.0005], [0.0098, 0.0362, 0.0005], [0.0019, 0.0362], [0.0019, 0.0326, 0.0004], [-0.0019, 0.0326, 0.0004], [-0.0019, 0.0362], [-0.0098, 0.0362, 0.0005]];
  S.add('steel', prism(rear, 0.007, 0.0195, { bevel: 0.0005, cs: 3 }), 0xd0d0d0);
  const front = [[-0.0017, h - 0.0005], [0.0017, h - 0.0005], [0.0016, 0.0362, 0.0007], [-0.0016, 0.0362, 0.0007]];
  S.add('steel', prism(front, 0.1695, 0.1765, { bevel: 0.0004, cs: 3 }), 0xd0d0d0);
  // задний торец: прорезь под ударник
  S.add('steel', box(0.006, 0.009, 0.0008, 0.0003), 0x404040).translate(0, 0.0165, 0.0003);
  const slide = new THREE.Group(); slide.name = 'slide';
  S.build(M, slide, 'slide');
  // тритиевые точки
  const dots = [];
  for (const [x, u, fz] of [[-0.0059, 0.0336, 0.007], [0.0059, 0.0336, 0.007], [0, 0.0334, 0.1695]]) {
    const ring = new THREE.CircleGeometry(0.00098, 14);
    ring.translate(x, u, -fz + 0.00028);
    dots.push(ring);
  }
  const dotGeo = new THREE.BufferGeometry();
  {
    const merged = dots.map((d) => d.toNonIndexed());
    const n = merged.reduce((a, g) => a + g.attributes.position.count, 0);
    const pos = new Float32Array(n * 3), nrm = new Float32Array(n * 3);
    let o = 0;
    for (const g of merged) { pos.set(g.attributes.position.array, o * 3); nrm.set(g.attributes.normal.array, o * 3); o += g.attributes.position.count; }
    dotGeo.setAttribute('position', new THREE.BufferAttribute(pos, 3)); dotGeo.setAttribute('normal', new THREE.BufferAttribute(nrm, 3));
  }
  const dotMesh = new THREE.Mesh(dotGeo, M.dots); dotMesh.frustumCulled = false; slide.add(dotMesh);
  root.add(slide);

  // --- ствол (виден в окне и на дульном срезе) ---
  P.add('steel', box(0.009, h - 0.0125 - 0.0005, 0.0405, 0.0006), 0xa8a8a8).translate(0.0002, (0.0125 + h - 0.0005) / 2, -0.0932);
  P.add('steel', lathe([[0.0046, 0.150], [0.0058, 0.150], [0.0058, 0.1866], [0.0046, 0.1866], [0.0046, 0.17]], 20, { u: 0.0168 }), 0x9a9a9a, 0.5);
  // --- рамка ---
  const upper = [[-0.006, 0.0], [0.165, 0.0], [0.1665, -0.0125, 0.002], [0.112, -0.0125], [0.06, -0.0135], [0.03, -0.019, 0.004], [0.0, -0.019], [-0.012, -0.013, 0.003], [-0.0148, -0.0055, 0.004], [-0.0085, 0.0]];
  P.add('poly', side(upper, 0.0215, { bevel: 0.0014, r: 0.0008 }));
  const guard = [[0.118, -0.008], [0.1175, -0.044, 0.004], [0.111, -0.0495, 0.005], [0.066, -0.0495, 0.006], [0.05, -0.036, 0.008], [0.048, -0.012]];
  const guardHole = [[0.061, -0.0135], [0.1095, -0.0135, 0.002], [0.108, -0.0438, 0.005], [0.068, -0.0438, 0.006], [0.0585, -0.031, 0.006], [0.0585, -0.016]];
  P.add('poly', side(guard, 0.0115, { bevel: 0.0016, holes: [guardHole] }));
  // планка: зубцы снизу
  const rail = [[0.118, -0.0122]];
  for (let i = 0; i < 4; i++) { const a = 0.121 + i * 0.011; rail.push([a, -0.0165], [a + 0.006, -0.0165], [a + 0.006, -0.0148], [a + 0.0088, -0.0148]); }
  rail.push([0.163, -0.0165], [0.1645, -0.0122]);
  P.add('poly', side(rail.map((p) => [p[0], p[1]]), 0.0185, { bevel: 0.0005 }));
  // рукоять (стиплинг) под углом ~22°
  const grip = [[0.004, -0.010], [0.052, -0.022, 0.006], [0.0065, -0.138, 0.005], [-0.0444, -0.118, 0.005], [-0.002, -0.012, 0.004]];
  P.add('grip', side(grip, 0.0295, { bevel: 0.0042, seg: 3 }));
  // выемки под большой палец и кнопка магазина
  P.add('poly', box(0.0026, 0.0068, 0.0068, 0.0008), 0x9a9a9a).translate(-0.0108, -0.0225, -0.0545);
  // затворная задержка и разобщитель
  P.add('steel', side([[0.068, -0.0032], [0.093, -0.0032, 0.001], [0.0955, 0.0008, 0.001], [0.074, 0.0017, 0.001], [0.068, 0.0002]], 0.0016, { x: -0.0116, bevel: 0.0004 }));
  for (const sx of [-1, 1]) P.add('steel', box(0.0013, 0.0052, 0.009, 0.0004)).translate(sx * 0.0112, -0.0058, -0.100);
  // штифты рамки
  for (const [ff, uu] of [[0.084, -0.0085], [0.020, -0.012]]) P.add('steel', cylX(0.0013, -0.0112, 0.0112, uu, ff, 10), 0xbbbbbb);

  // --- спуск (анимируется) ---
  const trigger = new THREE.Group(); trigger.position.set(0, -0.0135, -0.0895);
  const T = new Parts();
  T.add('poly', side([[0.0025, 0.0], [0.0062, -0.007, 0.003], [0.0052, -0.016, 0.004], [0.0072, -0.0232, 0.0015], [0.0035, -0.0238, 0.0015], [0.0012, -0.015, 0.004], [0.0015, -0.006, 0.002], [-0.001, 0.0]], 0.0062, { bevel: 0.0008 }));
  T.add('poly', side([[0.0055, -0.009], [0.0072, -0.010], [0.0068, -0.018], [0.0052, -0.017]], 0.0018, { bevel: 0.0003 }), 0x707070);
  T.build(M, trigger, 'trigger');
  root.add(trigger);

  // --- магазин (ось по рукояти) ---
  const mag = new THREE.Group(); mag.name = 'mag';
  const MG = new Parts();
  MG.add('poly', box(0.0212, 0.124, 0.0305, 0.0018), 0x8a8a8a).translate(0, -0.058, 0.0);
  MG.add('poly', box(0.0262, 0.0088, 0.0362, 0.0026), 0xffffff).translate(0, -0.1246, -0.0012);
  MG.add('poly', box(0.008, 0.004, 0.026, 0.0012), 0xb08040).translate(0, 0.0055, -0.002); // верхний патрон
  MG.build(M, mag, 'mag');
  const magBase = new THREE.Vector3(0, -0.018, -0.025);
  mag.position.copy(magBase); mag.rotation.x = -22 * D2R;
  root.add(mag);

  P.build(M, root, 'pistol');
  return {
    root, slide, trigger, mag, magBase, magAxis: new THREE.Vector3(0, -Math.cos(22 * D2R), Math.sin(22 * D2R)),
    muzzle: new THREE.Vector3(0, 0.0168, -0.19), eject: new THREE.Vector3(0.012, 0.024, -0.093),
    sightU: 0.0358,
  };
}

// ───────────────────────────── Дробовик (помповый, 870) ─────────────────────────────
function shellParts(P, red, brass, len = 0.068) {
  // гильза вдоль −Z: донце в z=0
  P.add(brass, lathe([[0.0, 0.0], [0.0104, 0.0], [0.0105, 0.0014], [0.0098, 0.0018], [0.0098, 0.0135], [0.0094, 0.0142]], 20), 0xffffff, 0.5);
  P.add(brass, lathe([[0.0, -0.0002], [0.0028, -0.0002], [0.0028, 0.0004]], 12), 0xd8d0c0, 0.5);
  P.add(red, lathe([[0.0092, 0.0128], [0.0093, len - 0.004], [0.0088, len - 0.001], [0.006, len], [0.0, len - 0.0015]], 20), 0xffffff, 0.7);
}

export function buildShell(M) {
  const g = new THREE.Group();
  const P = new Parts();
  shellParts(P, 'red', 'brass');
  P.build(M, g, 'shell');
  return g;
}

