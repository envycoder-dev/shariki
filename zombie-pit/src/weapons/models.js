  const T = new Parts();
  T.add('steel', side([[0.002, 0.0], [0.006, -0.008, 0.003], [0.0045, -0.018, 0.004], [0.0068, -0.0245, 0.0015], [0.0028, -0.025, 0.0015], [0.0006, -0.016, 0.004], [0.0012, -0.006, 0.002], [-0.002, 0.0]], 0.0058, { bevel: 0.0008 }));
  T.build(M, trigger, 'trigger');
  root.add(trigger);
  // цевьё (дерево, «кукурузный початок») + тяги затвора
  const pump = new THREE.Group(); pump.name = 'pump'; pump.position.set(0, 0, -0.29);
  const PP = new Parts();
  const prof = [[0.0112, 0.0], [0.0196, 0.0015], [0.0214, 0.006]];
  for (let k = 0; k < 13; k++) { const a = 0.011 + k * 0.0128; prof.push([0.0226, a], [0.0226, a + 0.0072], [0.0207, a + 0.0088], [0.0207, a + 0.0112]); }
