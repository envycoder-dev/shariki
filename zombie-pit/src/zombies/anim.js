export function idle(p, t, st) {
  neutral(p);
  const b = Math.sin(t * 1.6 + st.seed);
  p[S('spine', 0)] = 0.12 + 0.02 * b; p[S('neck', 0)] = 0.15; p[S('head', 2)] = st.tilt;
  p[S('armL', 0)] = -0.05 + 0.04 * b; p[S('armR', 0)] = -0.05 - 0.04 * b;
  p[S('jaw', 0)] = 0.1 + 0.15 * pos(Math.sin(t * 1.1 + st.seed));
}

// ------------------------------------------------------------------ клипы
// Каналы: 'кость.x|y|z', 'hips.px|py|pz', 'root.px|py|pz|rx|ry|rz'.
// Суффикс '*l' — умножить на «подъём» (полутолщина тела), '*k' — на длину голени.
function slotOf(name) {
  const [b, ax] = name.split('.');
  if (b === 'hips' && ax[0] === 'p') return HIPS_P + 'xyz'.indexOf(ax[1]);
  if (b === 'root') return (ax[0] === 'p' ? ROOT_P : ROOT_R) + 'xyz'.indexOf(ax[1]);
  return B[b] * 3 + 'xyz'.indexOf(ax);
}
const MIRROR_BONE = (n) => (n.endsWith('L') && B[n.slice(0, -1) + 'R'] !== undefined ? n.slice(0, -1) + 'R'
  : n.endsWith('R') && B[n.slice(0, -1) + 'L'] !== undefined ? n.slice(0, -1) + 'L' : n);

function compile(def, mirror = false) {
  const ch = [];
  for (const [rawName, keys] of Object.entries(def.ch)) {
    let [name, mul] = rawName.split('*');
    let sign = 1;
    if (mirror) {
      const [b, ax] = name.split('.');
      name = MIRROR_BONE(b) + '.' + ax;
      if (ax === 'y' || ax === 'z' || ax === 'px' || ax === 'ry' || ax === 'rz') sign = -1;
    }
    ch.push({ slot: slotOf(name), mul: mul || null, t: keys.map((k) => k[0]), v: keys.map((k) => k[1] * sign) });
  }
  return { ...def, ch };
}

function sampleKeys(c, u) {
  const t = c.t, v = c.v, n = t.length;
  if (u <= t[0]) return v[0];
  if (u >= t[n - 1]) return v[n - 1];
  let i = 1;
  while (t[i] < u) i++;
  const a = (u - t[i - 1]) / (t[i] - t[i - 1]);
  const s = a * a * (3 - 2 * a);
  return v[i - 1] + (v[i] - v[i - 1]) * s;
}

/** накладывает клип на позу out (абсолютно или аддитивно); u ∈ [0,1] */
export function sampleClip(clip, u, out, ctx, additive = false) {
  const touched = new Set();
  for (const c of clip.ch) {
    let v = sampleKeys(c, u);
    if (c.mul === 'l') v *= ctx.lift; else if (c.mul === 'k') v *= ctx.kneel;
    if (additive || touched.has(c.slot)) out[c.slot] += v; else { out[c.slot] = v; touched.add(c.slot); }
  }
}

