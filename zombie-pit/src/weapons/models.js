// ───────────────────────────── Граната Ф-1 (ось вдоль +Y) ─────────────────────────────
export function buildGrenadeGeometry() {
  const prof = [];
  for (let i = 0; i <= 40; i++) {
    const h = -0.046 + (i / 40) * 0.088;
    const k = h / 0.047;
    let r = 0.0285 * Math.sqrt(Math.max(0, 1 - k * k * (k < 0 ? 0.9 : 1.05)));
    if (h < -0.043) r = Math.min(r, 0.012);
    prof.push(new THREE.Vector2(Math.max(r, 0.0085), h));
  }
  prof.unshift(new THREE.Vector2(0, -0.0462));
  prof.push(new THREE.Vector2(0.0085, 0.044), new THREE.Vector2(0, 0.044));
  const g = new THREE.LatheGeometry(prof, 64);
  // «ананасная» насечка: 8 долей × 5 поясов
  const pos = g.attributes.position;
  for (let i = 0; i < pos.count; i++) {
    const x = pos.getX(i), y = pos.getY(i), z = pos.getZ(i);
    const r = Math.hypot(x, z); if (r < 0.009 || y < -0.04 || y > 0.034) continue;
    const a = Math.atan2(z, x) / (Math.PI * 2 / 8), fa = a - Math.floor(a), da = Math.min(fa, 1 - fa);
    const hy = (y + 0.04) / 0.0148, fy = hy - Math.floor(hy), dy = Math.min(fy, 1 - fy);
    const gr = Math.max(1 - Math.min(1, da / 0.09), 1 - Math.min(1, dy / 0.12));
    const s = 1 - 0.085 * gr * gr;
    pos.setX(i, x * s); pos.setZ(i, z * s);
  }
  g.computeVertexNormals();
  return g;
}

