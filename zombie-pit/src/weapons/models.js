  P.add('steel', lathe([[0.0112, 0.616], [0.0126, 0.621], [0.0126, 0.646], [0.0112, 0.6505], [0.004, 0.652], [0, 0.652]], 24, { u: -0.0255 }), 0xffffff, 0.7);
  P.add('steel', side([[0.604, 0.0055], [0.622, 0.0055], [0.622, -0.036], [0.604, -0.036]], 0.0175, { bevel: 0.0022, r: 0.004 }));
  // приклад (орех) с затыльником
